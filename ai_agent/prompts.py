import typing

import tools
from database import SQLiteMemoryStore

MISSING_USER_FACTS_STR: typing.Final = "Факты о пользователе отсутствуют."


def compile_system_prompt(user_id: str, db: SQLiteMemoryStore) -> str:
    """
    Формирует системный промпт для агента, обогащая его
    данными из долговременной памяти (SQLite).
    """
    user_facts: typing.Final = db.get_facts(user_id) or MISSING_USER_FACTS_STR

    # Базовый системный промпт, задающий роль и ограничения агента
    base_prompt: typing.Final = (
        "Ты — специализированный ИИ-агент поддержки для технических инженеров.\n"
        "Твоя задача — помогать пользователям, опираясь на доступные инструменты "
        "и контекст долгосрочной памяти. Отвечай кратко, профессионально и по делу.\n\n"
        "==================================================\n"
        "ДОЛГОВРЕМЕННАЯ ПАМЯТЬ О ТЕКУЩЕМ ПОЛЬЗОВАТЕЛЕ:\n"
        f"{user_facts}\n"
        "==================================================\n\n"
        "ПРАВИЛА РАБОТЫ С ИНСТРУМЕНТАМИ:\n"
        "- Если пользователь запрашивает информацию о своих доступах или правах на серверы, "
        f"ты ОБЯЗАН вызвать инструмент `{tools.PERMISSIONS_TOOL_NAME}`, "
        "передав туда числовой ID.\n"
        "- Никогда не придумывай доступы и ID из головы. Если данных нет в инструменте или памяти, "
        "так и скажи."
    )

    return base_prompt
